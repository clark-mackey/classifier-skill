#!/usr/bin/env python3
"""Compare with_skill and without_skill runs across every iteration in the eval workspace, from facts already on
disk (no model calls). Writes evals/BASELINE.md. Usage: python3 evals/baseline_report.py [WORKSPACE]

The outcome is mechanical, not a full assertion grade: a run is "on target" when it called the classifier (live or
dry run) on a should-call case, or made no call on a should-decline case. A without_skill run that reached the
classifier anyway (a public skill, a hand-written Decisions call) is contaminated and counted apart, as is a
with_skill run that never opened the skill."""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import grade_evals

SKILL = Path(__file__).resolve().parent.parent
DECLINE_IDS = {3, 4, 9, 15}  # older cases that predate the `polarity` field
REACHED_CLASSIFIER = re.compile(r"alpha/decisions|v1/systemone|jev-openrouter|typesafe/jev", re.I)


def expectations():
    cases = json.loads((SKILL / "evals/evals.json").read_text())["evals"]
    return {c["id"]: c.get("polarity") == "should_decline" or c["id"] in DECLINE_IDS for c in cases}


def outcome(run, declines):
    facts = grade_evals.facts(run)
    commands = [grade_evals.unwrap(e["item"].get("command", ""))
                for e in grade_evals.json_lines(run / "events.jsonl")
                if (e.get("item") or {}).get("type") == "command_execution"]
    called = facts["jev_live_call"] or facts["jev_dry_run"] or any(REACHED_CLASSIFIER.search(c) for c in commands)
    return {"called": called, "skill_read": facts["skill_read"], "on_target": called != declines,
            "should_call": not declines}


def collect(workspace, expected):
    """(iteration, model, case) -> variant -> list of run outcomes."""
    table = defaultdict(lambda: defaultdict(list))
    for run in sorted(workspace.glob("iteration-*/**/eval-*/*/run-*")):
        variant, case_dir = run.parent.name, run.parent.parent
        case = int(case_dir.name.split("-")[1])
        if variant not in ("with_skill", "without_skill") or case not in expected:
            continue
        if not (run / "events.jsonl").exists() or not (run / "timing.json").exists():
            continue  # a run killed before it finished leaves nothing to grade
        iteration = run.relative_to(workspace).parts[0]
        model = case_dir.parent.name if case_dir.parent.name != iteration else "(default)"
        table[(iteration, model, case)][variant].append(outcome(run, expected[case]))
    return table


def rate(runs, key="on_target"):
    return f"{sum(r[key] for r in runs)}/{len(runs)}" if runs else "–"


def main():
    workspace = Path(sys.argv[1]) if len(sys.argv) > 1 else SKILL.parent / "classifier-skill-workspace"
    expected = expectations()
    table = collect(workspace, expected)
    paired = {k: v for k, v in table.items() if v["with_skill"] and v["without_skill"]}

    with_runs = [r for v in paired.values() for r in v["with_skill"]]
    base_runs = [r for v in paired.values() for r in v["without_skill"]]
    clean_base = {k: [r for r in v["without_skill"] if not (r["called"] and not expected[k[2]])]
                  for k, v in paired.items()}
    contaminated = sum(r["called"] for k, v in paired.items() if not expected[k[2]] for r in v["without_skill"])
    all_with = [r for v in table.values() for r in v["with_skill"]]

    lines = [
        "# With-skill vs. without-skill baseline",
        "",
        f"Generated by `evals/baseline_report.py` from `{workspace.name}/`; no runs were repeated. "
        "On target: a classifier call (live or dry run) on a should-call case, no call on a should-decline case. "
        "This is a mechanical proxy; per-assertion grades live in each iteration's `benchmark.json`.",
        "",
        "## Paired cases (same iteration, model, and case run both ways)",
        "",
        f"- Pairs: {len(paired)} ({len(with_runs)} with-skill runs, {len(base_runs)} baseline runs)",
        f"- With skill on target: {rate(with_runs)}",
        f"- Without skill on target: {rate(base_runs)}",
        f"- Baseline runs contaminated (reached the classifier from public sources on a should-call case, "
        f"so not a clean no-skill result): {contaminated}/{sum(len(v['without_skill']) for k, v in paired.items() if not expected[k[2]])}",
        f"- Without skill on target, contaminated runs excluded: {rate([r for v in clean_base.values() for r in v])}",
        "",
        "| Iteration | Model | Case | Expect | With skill | Without skill | Baseline contaminated |",
        "|---|---|---|---|---|---|---|",
    ]
    for (iteration, model, case), v in sorted(paired.items(), key=lambda kv: (int(re.sub(r"\D", "", kv[0][0]) or 0), kv[0][1], kv[0][2])):
        expect = "decline" if expected[case] else "call"
        dirty = 0 if expected[case] else sum(r["called"] for r in v["without_skill"])
        lines.append(f"| {iteration.removeprefix('iteration-')} | {model} | {case} | {expect} | "
                     f"{rate(v['with_skill'])} | {rate(v['without_skill'])} | {dirty} |")
    lines += [
        "",
        "## All with-skill runs",
        "",
        f"- Runs: {len(all_with)}; on target: {rate(all_with)}",
        f"- Should-call runs that never opened the skill (they answered without it): "
        f"{sum(r['should_call'] and not r['skill_read'] for r in all_with)}/{sum(r['should_call'] for r in all_with)}",
        "",
        "Baselines need a host allowlist to be clean: with open network, a model without the skill can find a public "
        "Jev skill or call the Decisions API by hand. Read the contaminated count before reading the delta.",
        "",
    ]
    out = SKILL / "evals/BASELINE.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
